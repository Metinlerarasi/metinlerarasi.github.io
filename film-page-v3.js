const filmHero = document.querySelector('.film-cinema-hero');
const filmWeekTrack = document.querySelector('.film-week-track');
const filmSceneElements = [...document.querySelectorAll('.film-scene')];

function setFilmText(selector, value) {
  document.querySelectorAll(selector).forEach(element => { element.textContent = value; });
}

function selectFilm(id, updateHistory = true) {
  const film = filmProgram[id] || filmProgram['in-time'];
  filmHero.classList.add('is-changing');
  window.setTimeout(() => {
    document.documentElement.style.setProperty('--film-accent', film.accent);
    document.documentElement.style.setProperty('--film-accent-rgb', film.rgb);
    const heroImage = document.querySelector('[data-film-hero]');
    heroImage.src = film.hero;
    heroImage.alt = `${film.title} filminden bir sahne`;
    setFilmText('[data-film-index]', film.index);
    setFilmText('[data-film-date]', film.date);
    setFilmText('[data-film-genre]', film.genre);
    setFilmText('[data-film-title]', film.title);
    setFilmText('[data-film-logline]', film.logline);
    setFilmText('[data-film-director]', film.director);
    setFilmText('[data-film-year]', film.year);
    setFilmText('[data-film-theme]', film.theme);
    setFilmText('[data-film-reading]', film.reading);
    document.querySelectorAll('[data-film-trailer]').forEach(link => { link.href = film.trailer; link.setAttribute('aria-label', `${film.title} resmî fragmanını aç`); });
    filmSceneElements.forEach((scene, index) => {
      const sceneData = film.scenes[index];
      const image = scene.querySelector('img');
      image.src = sceneData[0];
      image.alt = `${film.title} filminden ${index + 1}. sahne`;
      scene.querySelector('[data-scene-number]').textContent = `SAHNE 0${index + 1}`;
      scene.querySelector('[data-scene-title]').textContent = sceneData[1];
      scene.querySelector('[data-scene-copy]').textContent = sceneData[2];
    });
    document.querySelectorAll('.film-week').forEach(button => {
      const active = button.dataset.film === id;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
      if (active) button.scrollIntoView({behavior:'smooth', block:'nearest', inline:'center'});
    });
    document.title = `${film.title} — Metinlerarası`;
    filmHero.classList.remove('is-changing');
    if (updateHistory) history.replaceState(null, '', `?film=${id}`);
  }, 280);
}

filmWeekTrack?.addEventListener('click', event => {
  const button = event.target.closest('[data-film]');
  if (!button) return;
  selectFilm(button.dataset.film);
  window.scrollTo({top:0, behavior:'smooth'});
});

const sceneObserver = new IntersectionObserver(entries => {
  entries.forEach(entry => entry.target.classList.toggle('is-visible', entry.isIntersecting));
}, {threshold:.35});
filmSceneElements.forEach(scene => sceneObserver.observe(scene));

const requestedFilm = new URLSearchParams(location.search).get('film');
selectFilm(filmProgram[requestedFilm] ? requestedFilm : 'in-time', false);
